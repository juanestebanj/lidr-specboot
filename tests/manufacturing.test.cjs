'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const build = (root, check = false) => require('../scripts/build-template.cjs').build(root, { check });
function fixture(fn) {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'specboot-build-'));
  const root = path.join(base, 'repo');
  fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
  fs.mkdirSync(path.join(root, 'ai-specs/skills/example'), { recursive: true });
  fs.mkdirSync(path.join(root, '.cursor/rules'), { recursive: true });
  fs.writeFileSync(path.join(root, '.cursor/rules/use-base-rules.mdc'), 'adapter discovery\n');
  fs.writeFileSync(path.join(root, 'docs/base-standards.md'), 'canonical standards\n');
  fs.writeFileSync(path.join(root, 'ai-specs/specboot-instructions.md'), 'customer onboarding\n');
  fs.writeFileSync(path.join(root, 'ai-specs/skills/example/SKILL.md'), 'example workflow\n');
  try { fn(root, base); } finally { fs.rmSync(base, { recursive: true, force: true }); }
}
const output = root => path.join(root, 'packages/specboot/template');
const manifest = root => path.join(root, 'packages/specboot/template-manifest.json');
function snapshot(root) {
  const files = {};
  function walk(dir, prefix = '') {
    for (const name of fs.readdirSync(dir).sort()) {
      const p = path.join(dir, name), rel = prefix + name;
      if (fs.lstatSync(p).isDirectory()) walk(p, rel + '/');
      else files[rel] = fs.readFileSync(p).toString('base64');
    }
  }
  walk(path.join(root, 'packages/specboot'));
  return files;
}
test('T31: generation copies canonical bytes and records exact portable digests', () => fixture(root => {
  build(root);
  const m = JSON.parse(fs.readFileSync(manifest(root), 'utf8'));
  assert.equal(m.schemaVersion, 1);
  assert.deepEqual(m.files.map(x => x.path), [...m.files.map(x => x.path)].sort());
  assert.equal(m.files.length, 4);
  for (const row of m.files) {
    const source = fs.readFileSync(path.join(root, row.source));
    const target = fs.readFileSync(path.join(output(root), row.path));
    assert.deepEqual(target, source);
    const digest = crypto.createHash('sha256').update(source).digest('hex');
    assert.equal(row.sourceSha256, digest);
    assert.equal(row.targetSha256, digest);
    assert.ok(!path.isAbsolute(row.source) && !row.source.includes('\\'));
  }
}));
test('T32: repeated generation is byte-identical and check mode succeeds', () => fixture(root => {
  build(root); const before = snapshot(root); build(root); build(root, true);
  assert.deepEqual(snapshot(root), before);
}));
test('T33: changed generated bytes fail check without repairing evidence', () => fixture(root => {
  build(root); const p = path.join(output(root), 'docs/base-standards.md');
  fs.writeFileSync(p, 'tampered'); const before = snapshot(root);
  assert.throws(() => build(root, true), /drift/i);
  assert.deepEqual(snapshot(root), before);
}));
test('T34: missing extra and modified manifest entries fail non-mutating checks', () => fixture(root => {
  for (const mutate of [
    () => fs.unlinkSync(path.join(output(root), 'docs/base-standards.md')),
    () => fs.writeFileSync(path.join(output(root), 'extra.txt'), 'extra'),
    () => fs.writeFileSync(manifest(root), '{}\n')
  ]) {
    build(root); mutate(); const before = snapshot(root);
    assert.throws(() => build(root, true), /drift/i);
    assert.deepEqual(snapshot(root), before);
  }
}));
test('T35: canonical directory symlink is rejected before artifact writes', () => fixture((root, base) => {
  build(root); const before = snapshot(root);
  fs.symlinkSync(path.join(root, 'docs'), path.join(root, 'ai-specs/linked'), 'junction');
  assert.throws(() => build(root), /symlink|symbolic/i);
  assert.deepEqual(snapshot(root), before);
}));
test('T36: managed output symlink is rejected without following its target', () => fixture((root, base) => {
  build(root); const external = path.join(base, 'external'); fs.mkdirSync(external);
  fs.writeFileSync(path.join(external, 'marker'), 'unchanged');
  fs.symlinkSync(external, path.join(output(root), 'linked'), 'junction');
  assert.throws(() => build(root), /symlink|symbolic/i);
  assert.equal(fs.readFileSync(path.join(external, 'marker'), 'utf8'), 'unchanged');
}));
test('T37: managed parent symlink is rejected before creating external output', () => fixture((root, base) => {
  const external = path.join(base, 'external'); fs.mkdirSync(external);
  fs.symlinkSync(external, path.join(root, 'packages'), 'junction');
  assert.throws(() => build(root), /symlink|symbolic/i);
  assert.deepEqual(fs.readdirSync(external), []);
}));
test('T38: missing canonical root fails before replacing existing artifacts', () => fixture(root => {
  build(root); const before = snapshot(root); fs.renameSync(path.join(root, 'docs'), path.join(root, 'saved-docs'));
  assert.throws(() => build(root), /docs|canonical/i);
  assert.deepEqual(snapshot(root), before);
}));
test('T39: generation preserves source-only repository artifacts', () => fixture(root => {
  fs.writeFileSync(path.join(root, 'README.md'), 'source-owned');
  fs.mkdirSync(path.join(root, 'openspec')); fs.writeFileSync(path.join(root, 'openspec/spec.md'), 'source contract');
  build(root);
  assert.equal(fs.readFileSync(path.join(root, 'README.md'), 'utf8'), 'source-owned');
  assert.equal(fs.readFileSync(path.join(root, 'openspec/spec.md'), 'utf8'), 'source contract');
  assert.ok(!fs.existsSync(path.join(output(root), 'openspec')));
}));
test('T40: regeneration removes stale managed files and includes new canonical files', () => fixture(root => {
  build(root); fs.writeFileSync(path.join(output(root), 'extra.txt'), 'stale');
  fs.writeFileSync(path.join(root, 'docs/new.md'), 'new canonical'); build(root); build(root, true);
  assert.ok(!fs.existsSync(path.join(output(root), 'extra.txt')));
  assert.equal(fs.readFileSync(path.join(output(root), 'docs/new.md'), 'utf8'), 'new canonical');
}));
